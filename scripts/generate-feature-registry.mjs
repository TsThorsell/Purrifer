import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");
const featuresRoot = path.join(projectRoot, "src", "features");
const generatedRoot = path.join(projectRoot, "src", "app", "registry", "generated");

function toIdentifier(featureName, suffix) {
  const normalized = featureName
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((segment, index) => {
      const lower = segment.toLowerCase();
      if (index === 0) {
        return lower;
      }
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join("");

  return `${normalized}${suffix}`;
}

function toImportPath(...segments) {
  return `@features/${segments.join("/")}`;
}

function writeGeneratedFile(filename, header, importLines, exportName, identifiers) {
  const filePath = path.join(generatedRoot, filename);
  const body = [
    "// This file is auto-generated by scripts/generate-feature-registry.mjs.",
    header,
    "",
    ...importLines,
    "",
    `export const ${exportName} = [`,
    ...identifiers.map((identifier) => `  ${identifier},`),
    "];",
    ""
  ].join("\n");

  const previous = existsSync(filePath) ? readFileSync(filePath, "utf8") : null;
  if (previous !== body) {
    writeFileSync(filePath, body, "utf8");
  }
}

export function generateFeatureRegistry(root = projectRoot) {
  const featureDirectories = readdirSync(path.join(root, "src", "features"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const sliceImports = [];
  const sliceIdentifiers = [];
  const routeImports = [];
  const routeIdentifiers = [];
  const mainImports = [];
  const mainIdentifiers = [];
  const preloadImports = [];
  const preloadIdentifiers = [];
  const shellImports = [];
  const shellIdentifiers = [];

  for (const featureName of featureDirectories) {
    const featureRoot = path.join(root, "src", "features", featureName);
    const sliceManifestPath = path.join(featureRoot, "slice.manifest.ts");
    const routeHostPath = path.join(featureRoot, "renderer", "routeHost.tsx");
    const shellHostPath = path.join(featureRoot, "renderer", "shellHost.tsx");
    const mainHostPath = path.join(featureRoot, "main", "mainHost.ts");
    const preloadHostPath = path.join(featureRoot, "preload", "preloadHost.ts");

    if (existsSync(sliceManifestPath)) {
      const identifier = toIdentifier(featureName, "SliceManifestModule");
      sliceImports.push(`import * as ${identifier} from "${toImportPath(featureName, "slice.manifest")}";`);
      sliceIdentifiers.push(identifier);
    }

    if (existsSync(routeHostPath)) {
      const identifier = toIdentifier(featureName, "RouteHostModule");
      routeImports.push(`import * as ${identifier} from "${toImportPath(featureName, "renderer", "routeHost")}";`);
      routeIdentifiers.push(identifier);
    }

    if (existsSync(shellHostPath)) {
      const identifier = toIdentifier(featureName, "ShellHostModule");
      shellImports.push(`import * as ${identifier} from "${toImportPath(featureName, "renderer", "shellHost")}";`);
      shellIdentifiers.push(identifier);
    }

    if (existsSync(mainHostPath)) {
      const identifier = toIdentifier(featureName, "MainHostModule");
      mainImports.push(`import * as ${identifier} from "${toImportPath(featureName, "main", "mainHost")}";`);
      mainIdentifiers.push(identifier);
    }

    if (existsSync(preloadHostPath)) {
      const identifier = toIdentifier(featureName, "PreloadHostModule");
      preloadImports.push(`import * as ${identifier} from "${toImportPath(featureName, "preload", "preloadHost")}";`);
      preloadIdentifiers.push(identifier);
    }
  }

  mkdirSync(generatedRoot, { recursive: true });

  writeGeneratedFile(
    "generatedSliceManifestModules.ts",
    "",
    sliceImports,
    "generatedSliceManifestModules",
    sliceIdentifiers
  );
  writeGeneratedFile(
    "generatedRouteHostModules.ts",
    "",
    routeImports,
    "generatedRouteHostModules",
    routeIdentifiers
  );
  writeGeneratedFile(
    "generatedMainHostModules.ts",
    "",
    mainImports,
    "generatedMainHostModules",
    mainIdentifiers
  );
  writeGeneratedFile(
    "generatedPreloadHostModules.ts",
    "",
    preloadImports,
    "generatedPreloadHostModules",
    preloadIdentifiers
  );
  writeGeneratedFile(
    "generatedShellHostModules.ts",
    "",
    shellImports,
    "generatedShellHostModules",
    shellIdentifiers
  );

  return generatedRoot;
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  generateFeatureRegistry();
}
